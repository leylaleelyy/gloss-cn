export function t(lang: UILanguage, key: string, vars?: Record<string, string | number>): string {
  let s = (lang === "zh" ? ZH[key] : undefined) ?? EN[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function actionLabel(lang: UILanguage, action: Action): string {
  return t(lang, `action.${action}.label`);
}
export function actionHint(lang: UILanguage, action: Action): string {
  return t(lang, `action.${action}.hint`);
}

export function useI18n() {
  const stored = useStore((s) => s.settings.uiLanguage);
  // The server always renders English, so the first client render must too.
  // After mount, the reader's saved language takes over without a hydration mismatch.
  const [mounted, setMounted] = useState(false);
  useEffect(() => setMounted(true), []);
  const lang = mounted ? stored : "en";
  return useMemo(() => ({ lang, t: (key: string, vars?: Record<string, string | number>) => t(lang, key, vars) }), [lang]);
}
